CREATE DATABASE IF NOT EXISTS saree_aura CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE saree_aura;
SET FOREIGN_KEY_CHECKS=0;
DROP TABLE IF EXISTS product_tags, tags, products, categories;
SET FOREIGN_KEY_CHECKS=1;
CREATE TABLE categories (
  id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(60) NOT NULL,
  slug VARCHAR(60) NOT NULL UNIQUE,
  section ENUM('sarees','dresses','accessories') NOT NULL,
  sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE products (
  id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  category_id INT UNSIGNED NOT NULL,
  name VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL UNIQUE,
  price DECIMAL(10,2) NOT NULL,
  image_path VARCHAR(255) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  FOREIGN KEY (category_id) REFERENCES categories(id)
) ENGINE=InnoDB;
CREATE TABLE tags (
  id INT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(60) NOT NULL UNIQUE,
  type ENUM('material','occasion') NOT NULL
) ENGINE=InnoDB;
CREATE TABLE product_tags (
  product_id INT UNSIGNED NOT NULL,
  tag_id INT UNSIGNED NOT NULL,
  PRIMARY KEY (product_id, tag_id),
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
  FOREIGN KEY (tag_id) REFERENCES tags(id) ON DELETE CASCADE
) ENGINE=InnoDB;
